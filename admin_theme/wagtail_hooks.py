"""
Apply the PLT "cheesecake" design-system theme and PlayLoveToys branding to the Wagtail admin.

cheesecake-admin.css only overrides Wagtail's documented ``--w-color-*`` / ``--w-font-sans``
custom properties and is generated by ``scripts/build_admin_theme.py``; see README.md.
branding.css sizes the logos used by the ``wagtailadmin/*`` template overrides.
"""

from django.utils.html import format_html
from wagtail import hooks
from wagtail.admin.staticfiles import versioned_static

CHEESECAKE_ADMIN_CSS = 'admin_theme/css/cheesecake-admin.css'
BRANDING_CSS = 'admin_theme/css/branding.css'


@hooks.register('insert_global_admin_css')
def cheesecake_admin_css():
    return format_html(
        '<link rel="stylesheet" href="{}"><link rel="stylesheet" href="{}">',
        versioned_static(CHEESECAKE_ADMIN_CSS),
        versioned_static(BRANDING_CSS),
    )
